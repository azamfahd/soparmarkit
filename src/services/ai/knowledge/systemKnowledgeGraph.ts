/**
 * Diagnostic Engine: Answers "Why" questions (لماذا مبيعات كذا صفر، لماذا الأرباح سالبة، لماذا الرقم كذا).
 */
export function getWhyExplanationForQuery(queryText: string, contextData?: any): string | null {
  const clean = queryText.toLowerCase().trim();

  // 1. Why are sales zero / low?
  if (/(لماذا|ليش|سبب|ليه|ما سبب) (المبيعات|مبيعات اليوم|المبيعات صفر|المبيعات منخفضة|المبيعات معدومة)/i.test(clean) ||
      /(مبيعات اليوم صفر|ليش مافي مبيعات|لماذا المبيعات 0)/i.test(clean)) {
    const metric = SYSTEM_FINANCIAL_METRICS_AND_FORMULAS.sales_revenue;
    return `🔍 **تشخيص محاسبي: أسباب ظهور المبيعات (0.00) أو انخفاضها:**\n\n` +
      `• **طريقة احتساب المبيعات في النظام:**\n` +
      `  ${metric.exactFormula}\n\n` +
      `📌 **الأسباب المحاسبية والتشغيلية المباشرة:**\n` +
      `  1. **عدم إصدار فواتير اليوم بعد:** لم يتم تسجيل أي فاتورة بيع جديدة من شاشة الكاشير في هذا اليوم حتى اللحظة.\n` +
      `  2. **فلترة التاريخ:** قد يكون التقرير محدد على تاريخ يوم لم تفتح فيه الكاشير أو يوم عطلة.\n` +
      `  3. **إلغاء أو ترجيع العمليات:** إذا تم إلغاء كافة فواتير اليوم أو ترجيعها بالكامل.\n\n` +
      `💡 **للتحقق السريع:** افتح شاشة **سجل المبيعات (History)** وتأكد من وجود فواتير مسجلة بتاريخ اليوم.`;
  }

  // 2. Why is net profit negative or lower than expected?
  if (/(لماذا|ليش|سبب|ليه|ما سبب) (الارباح|الربح|صافي الربح|الارباح سالبة|الربح سالب|الارباح منخفضة|المكسب قليل)/i.test(clean) ||
      /(الارباح سالبة|ليش الارباح كذا|لماذا الربح قليل)/i.test(clean)) {
    const metric = SYSTEM_FINANCIAL_METRICS_AND_FORMULAS.net_profit;
    return `🔍 **تشخيص محاسبي: أسباب ظهور صافي الأرباح بالسالب أو انخفاضها:**\n\n` +
      `• **المعادلة المعتمدة لحساب صافي الربح:**\n` +
      `  ${metric.exactFormula}\n\n` +
      `📌 **الأسباب الشائعة لانخفاض الأرباح أو ظهورها بالسالب:**\n` +
      `  1. **المسحوبات والمصاريف النقدية:** عند تسجيل مسحوبات نقدية (سحب كاش للمالك، فواتير كهرباء، إيجار، عمالة) تتجاوز قيمتها مجمل أرباح المبيعات خلال الفترة، فإن صافي الربح يتحول تلقائياً إلى قيمة سالبة لتوضيح العجز.\n` +
      `  2. **تسجيل سعر التكلفة غير دقيق:** إذا تم إدخال سعر تكلفة الشراء أعلى من أو مساوياً لسعر البيع بالخطأ عند إضافة المنتجات.\n` +
      `  3. **خصومات مرتفعة:** منح خصومات كبيرة على الفواتير التهمت هامش الربح التجاري.\n\n` +
      `💡 **الحل والمراجعة:** راجع شاشة **تصفية الصندوق والملاحظات** للتأكد من بنود المسحوبات، وتأكد من أسعار التكلفة في صفحة **المخزون**.`;
  }

  // 3. Why are customer debts high?
  if (/(لماذا|ليش|سبب|ليه|ما سبب) (ديون العملاء|الديون مرتفعة|ديون الزبائن|الذمم)/i.test(clean) ||
      /(ديون العملاء مرتفعة|ليش الديون كثيرة)/i.test(clean)) {
    const metric = SYSTEM_FINANCIAL_METRICS_AND_FORMULAS.customer_debt;
    return `🔍 **تشخيص محاسبي: أسباب ارتفاع ديون العملاء والذمم المدينة:**\n\n` +
      `• **معادلة احتساب ديون العملاء:**\n` +
      `  ${metric.exactFormula}\n\n` +
      `📌 **الأسباب المباشرة لارتفاع الديون:**\n` +
      `  1. **كثرة المبيعات الآجلة (بالدين):** تكرار البيع الآجل للزبائن دون وضع حدود ائتمانية ملزمة.\n` +
      `  2. **عدم تسجيل سندات القبض أولاً بأول:** استلام دفعات كاش من الزبائن دون توثيقها عبر زر "تسديد دين" في شاشة العملاء.\n\n` +
      `💡 **التوصية:** توجه لقسم **العملاء والديون** واستخرج كشوفات الحساب للمدينين للبدء في جدولة التحصيل.`;
  }

  // 4. Why cash drawer difference (عجز أو فائض الصندوق)
  if (/(لماذا|ليش|سبب|ليه|ما سبب) (عجز الصندوق|فائض الصندوق|فرق الدرج|اختلاف الصندوق|الدرج غير مطابق)/i.test(clean)) {
    const metric = SYSTEM_FINANCIAL_METRICS_AND_FORMULAS.cash_drawer_reconciliation;
    return `🔍 **تشخيص محاسبي: أسباب وجود فارق (عجز أو فائض) في صندوق النقدية:**\n\n` +
      `• **معادلة مطابقة الصندوق:**\n` +
      `  ${metric.exactFormula}\n\n` +
      `📌 **أسباب ظهور العجز أو الفائض في الدرج:**\n` +
      `  1. **مصاريف كاش غير مسجلة:** سحب نقود من الدرج لشراء احتياجات للمحل أو للمالك دون الضغط على زر "سحب نقدي".\n` +
      `  2. **أخطاء في إرجاع الباقي:** تسليم الزبون مبلغاً أكبر أو أقل من الباقي المستحق.\n` +
      `  3. **خلط بين الكاش والآجل:** تسجيل فاتورة نقدية بينما العميل أخذ البضاعة ديناً (أو العكس).\n\n` +
      `💡 **الإجراء:** قم بتوثيق أي سحب كاش عبر زر "سحب نقدي" فور خروج النقود من الدرج.`;
  }

  // 5. Why inventory valuation differs from sales revenue
  if (/(لماذا|ليش|سبب|ليه|الفرق بين) (راس المال والبيع|رأس مال المخزون والمبيعات المتوقعة|تقييم المخزون)/i.test(clean)) {
    return `🔍 **شرح محاسبي: الفرق بين رأس مال المخزون وقيمة المبيعات المتوقعة:**\n\n` +
      `• **رأس المال بالتكلفة (Cost Valuation):** هو إجمالي ما دفعته لشراء البضائع المتوفرة بالمخزن = مجموع (الكمية × سعر تكلفة الشراء).\n` +
      `• **المبيعات المتوقعة (Retail Valuation):** هو إجمالي الإيراد المتوقع عند بيع كل هذه الكميات = مجموع (الكمية × سعر البيع للزبون).\n` +
      `• **الفارق بينهما:** يمثل **مجمل الأرباح الكامنة والمتوقعة** للمتجر عند تصفية وبيع كامل المخزون الحالي.`;
  }

  return null;
}

/**
 * Universal tokenized knowledge search matching any word, concept, card, section, or procedure.
 */
export function searchUniversalKnowledge(queryText: string): { type: string; title: string; content: string } | null {
  const clean = queryText.toLowerCase().trim();

  // 1. Check sections
  const section = getSectionDetails(clean);
  if (section) {
    return {
      type: 'SECTION',
      title: `قسم ${section.arabicName} (${section.englishName})`,
      content: `• الهدف الأساسي: ${section.primaryPurpose}\n• الوصف: ${section.detailedDescription}\n• أبرز المميزات: ${section.keyFeatures.slice(0, 4).join(' | ')}`
    };
  }

  // 2. Check cards
  for (const card of Object.values(SYSTEM_CARDS_AND_WIDGETS)) {
    if (clean.includes(card.id) || clean.includes(card.name.toLowerCase())) {
      return {
        type: 'CARD',
        title: card.name,
        content: `• الموقع: ${card.location}\n• الهدف: ${card.purpose}\n• المعادلة: ${card.calculationFormula}`
      };
    }
    for (const alias of card.aliases) {
      if (clean.includes(alias.toLowerCase())) {
        return {
          type: 'CARD',
          title: card.name,
          content: `• الموقع: ${card.location}\n• الهدف: ${card.purpose}\n• المعادلة: ${card.calculationFormula}`
        };
      }
    }
  }

  // 3. Check financial metrics
  for (const metric of Object.values(SYSTEM_FINANCIAL_METRICS_AND_FORMULAS)) {
    if (clean.includes(metric.id) || clean.includes(metric.arabicName.toLowerCase())) {
      return {
        type: 'METRIC',
        title: metric.arabicName,
        content: `• التعريف: ${metric.definition}\n• المعادلة: ${metric.exactFormula}\n• الأهمية: ${metric.whyItMatters}`
      };
    }
    for (const alias of metric.aliases) {
      if (clean.includes(alias.toLowerCase())) {
        return {
          type: 'METRIC',
          title: metric.arabicName,
          content: `• التعريف: ${metric.definition}\n• المعادلة: ${metric.exactFormula}\n• الأهمية: ${metric.whyItMatters}`
        };
      }
    }
  }

  return null;
}
