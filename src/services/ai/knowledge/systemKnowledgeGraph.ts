/**
 * Searches the system dictionary by token or phrase.
 */
export function lookupSystemDictionary(queryText: string): SystemDictionaryEntry[] {
  const clean = queryText.toLowerCase().trim();
  const matches: SystemDictionaryEntry[] = [];

  for (const entry of Object.values(SYSTEM_DICTIONARY)) {
    if (
      clean.includes(entry.id) ||
      clean.includes(entry.arabicName.toLowerCase()) ||
      clean.includes(entry.englishName.toLowerCase()) ||
      entry.synonyms.some(s => clean.includes(s.toLowerCase()))
    ) {
      matches.push(entry);
    }
  }

  return matches;
}

