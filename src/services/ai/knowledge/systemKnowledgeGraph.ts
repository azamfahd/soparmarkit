function cleanArabicText(str: string): string {
  if (!str) return '';
  return str
    .toLowerCase()
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[\u064B-\u065F\u0670]/g, '')
    .replace(/[^\w\s\u0600-\u06FF]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Returns specific details about a single section by key, name, or alias.
 */
export function getSectionDetails(queryText: string): SystemSectionInfo | null {
  const clean = cleanArabicText(queryText);

  for (const section of Object.values(SYSTEM_SECTIONS)) {
    if (clean.includes(cleanArabicText(section.id)) || clean.includes(cleanArabicText(section.tabKey))) return section;
    if (clean.includes(cleanArabicText(section.arabicName)) || clean.includes(cleanArabicText(section.englishName))) return section;
    for (const alias of section.aliases) {
      if (clean.includes(cleanArabicText(alias))) return section;
    }
  }

  // Keyword-based section resolution
  if (clean.includes('استيراد') || clean.includes('اكسل') || clean.includes('رفع سلع') || clean.includes('ملف سلع')) {
    return SYSTEM_SECTIONS['smart-import'] || null;
  }
  if (clean.includes('كاشير') || clean.includes('نقطة بيع') || clean.includes('نقطه بيع') || clean.includes('شاشة البيع') || (clean.includes('مبيعات') && clean.includes('قسم'))) {
    return SYSTEM_SECTIONS['pos'] || null;
  }
  if (clean.includes('مخزون') || clean.includes('منتجات') || clean.includes('اصناف') || clean.includes('سلع')) {
    return SYSTEM_SECTIONS['inventory'] || null;
  }
  if (clean.includes('عملاء') || clean.includes('زبائن') || clean.includes('زبون') || clean.includes('ديون عملاء')) {
    return SYSTEM_SECTIONS['customers'] || null;
  }
  if (clean.includes('موردين') || clean.includes('مورد') || clean.includes('شركات') || clean.includes('موزعين')) {
    return SYSTEM_SECTIONS['suppliers'] || null;
  }
  if (clean.includes('سجل') || clean.includes('فواتير سابقة') || clean.includes('طباعة فاتورة')) {
    return SYSTEM_SECTIONS['invoices'] || null;
  }
  if (clean.includes('تصفية') || clean.includes('صندوق') || clean.includes('درج') || clean.includes('نقدية') || clean.includes('ملاحظات')) {
    return SYSTEM_SECTIONS['notes'] || null;
  }
  if (clean.includes('تحليلات') || clean.includes('مستشار') || clean.includes('توصيات') || clean.includes('تشخيص')) {
    return SYSTEM_SECTIONS['analytics'] || null;
  }
  if (clean.includes('اعدادات') || clean.includes('ضبط') || clean.includes('ترخيص') || clean.includes('امان') || clean.includes('نسخ احتياطي')) {
    return SYSTEM_SECTIONS['settings'] || null;
  }

  return null;
}

